import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDirectory = path.join(repositoryRoot, "supabase", "migrations");
const outputPath = path.join(repositoryRoot, "supabase", "master.sql");
const checkOnly = process.argv.includes("--check");

const migrationNames = (await readdir(migrationsDirectory))
  .filter((name) => /^\d{14}_[a-z0-9_]+\.sql$/.test(name))
  .sort((left, right) => left.localeCompare(right));

if (migrationNames.length === 0) {
  throw new Error("No Supabase migrations were found.");
}

const migrations = await Promise.all(
  migrationNames.map(async (name) => {
    const sql = (await readFile(path.join(migrationsDirectory, name), "utf8")).trim();
    const checksum = createHash("sha256").update(sql).digest("hex");
    return { name, sql, checksum };
  }),
);

const sourceManifest = migrations
  .map(({ name, checksum }) => `--   ${name}  sha256:${checksum}`)
  .join("\n");

const migrationSql = migrations
  .map(({ name, sql }) => `\n-- ============================================================================\n-- Migration: ${name}\n-- ============================================================================\n\n${sql}\n`)
  .join("");

const output = `-- SOUTH EMERALD INVENTORY & SALES — MASTER DATABASE INSTALLER
--
-- GENERATED FILE: do not edit this file directly.
-- Run \`npm run db:master\` after changing a file in supabase/migrations.
--
-- Purpose:
--   Installs the complete application database into a NEW Supabase project.
--   It includes tables, types, indexes, triggers, functions, grants, RLS policies,
--   reporting functions, RBAC hardening, and endpoint rate limiting.
--
-- Safety:
--   This installer intentionally stops if the application schema already exists.
--   Use the ordered migrations for upgrades to an existing database.
--   Development seed and reset scripts are intentionally excluded.
--
-- Source migrations (${migrations.length}):
${sourceManifest}

begin;

do $master_install_preflight$
begin
  if to_regclass('public.profiles') is not null
     or to_regtype('public.app_role') is not null then
    raise exception using
      errcode = '55000',
      message = 'South Emerald application schema already exists.',
      hint = 'Use the ordered files in supabase/migrations for upgrades. Run master.sql only on a new project.';
  end if;
end
$master_install_preflight$;
${migrationSql}
-- Ensure PostgREST refreshes its API schema after the transaction commits.
notify pgrst, 'reload schema';

commit;
`;

if (checkOnly) {
  let existing = "";
  try {
    existing = await readFile(outputPath, "utf8");
  } catch {
    throw new Error("supabase/master.sql is missing. Run `npm run db:master`.");
  }

  if (existing !== output) {
    throw new Error("supabase/master.sql is out of date. Run `npm run db:master`.");
  }

  console.log(`supabase/master.sql is current (${migrations.length} migrations).`);
} else {
  await writeFile(outputPath, output, "utf8");
  console.log(`Generated supabase/master.sql from ${migrations.length} migrations.`);
}
